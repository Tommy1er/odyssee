import assert from 'node:assert/strict';
import {SkyOptics} from '../src/sky-optics.js';
const optics=new SkyOptics(new Float32Array(2048));
const ordinary={pos:[0,0,0],lensing:true};
const near={pos:[0,0,10],lensing:true,target:{type:'blackhole',xyz:[0,0,0],radiusLy:1}};
const programs=[];
const renderer={async compileAsync(scene){programs.push(scene.children[0].material);}};
await optics.prepare(renderer,ordinary);
assert(!optics.material.fragmentShader.includes('traceBlackHole'));
assert(!optics.material.fragmentShader.includes('bhStep'));
assert.equal(optics.blackHoleMaterial,undefined);
const uniforms=optics.material.uniforms;
await optics.prepare(renderer,{...near,pos:[0,0,1000]});
await optics.prepare(renderer,{...near,lensing:false});
assert.equal(programs.length,1);
await optics.prepare(renderer,near);
assert(optics.material.fragmentShader.includes('traceBlackHole'));
assert(optics.material.fragmentShader.includes('i<520'));
assert.equal(optics.material.uniforms,uniforms);
assert.equal(programs.length,2);
uniforms.exposure.value=3;
await optics.prepare(renderer,ordinary);
assert.equal(optics.material,programs[0]);
assert.equal(optics.material.uniforms.exposure.value,3);
await optics.prepare(renderer,near);
assert.equal(optics.material,programs[1]);
assert.equal(programs.length,2);
console.log('PASS ordinary startup excludes black-hole GLSL; near/lensing gating; shared uniforms; both variants cached');
