"""Build src/cie-1931.js from the official CIE 1931 2-degree colour-matching functions in data/ (CIE 2019,
DOI 10.25039/CIE.DS.xvudnb9b), 1 nm steps, 360-830 nm. Reproducible: checks the row count and wavelength grid."""
import csv, hashlib, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / "data" / "CIE_xyz_1931_2deg.csv"
rows = [r for r in csv.reader(src.open()) if r]
lam = [int(float(r[0])) for r in rows]
assert lam == list(range(360, 831)), "unexpected wavelength grid"
flat = [round(float(v), 9) for r in rows for v in r[1:4]]
sha = hashlib.sha256(src.read_bytes()).hexdigest()
out = root / "src" / "cie-1931.js"
out.write_text(
    "// CIE 1931 2° standard observer colour-matching functions x̄, ȳ, z̄, 360–830 nm in 1 nm steps.\n"
    "// Source: data/CIE_xyz_1931_2deg.csv (CIE 2019, DOI 10.25039/CIE.DS.xvudnb9b), SHA-256 " + sha + ".\n"
    "// Generated by scripts/build-cie.py; do not edit by hand.\n"
    "export const CIE_START = 360, CIE_END = 830;\n"
    "export const CIE_1931 = new Float64Array(" + json.dumps(flat, separators=(",", ":")) + ");\n")
print("wrote", out, len(rows), "rows, sha256", sha[:16])
