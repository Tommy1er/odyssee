import fs from 'node:fs';
import {NEBULA_PHYSICS,calibrate} from '../src/nebulae.js';
import {directionalRGB} from '../src/nebula-direction.js';
const latitude=8,longitude=16,tables={};
for(const id of Object.keys(NEBULA_PHYSICS)){
 const c=calibrate({id,type:id==='pillars'?'pillars':'nebula',d:1,radiusLy:1});
 const ref=directionalRGB(c,[0,0,1]),rows=[];
 for(let i=0;i<=latitude;i++){
  const th=i*Math.PI/latitude,row=[];
  for(let j=0;j<longitude;j++){
   if((i===0||i===latitude)&&j){row.push(row[0]);continue;}
   const ph=j*2*Math.PI/longitude,v=directionalRGB(c,[Math.sin(th)*Math.cos(ph),Math.sin(th)*Math.sin(ph),Math.cos(th)]);
   row.push(v.map((x,k)=>Number((x/ref[k]).toPrecision(8))));
  }rows.push(row);
 }
 tables[id]=rows;console.log('Integrated',id);
}
fs.writeFileSync('src/nebula-direction-data.js','// Generated by scripts/build-nebula-directions.mjs. Procedural model, not measured anisotropy.\nexport const nebulaDirections='+JSON.stringify({latitude,longitude,tables})+';\n');
